-- ---------------------------------------------------------------------------
-- listings
-- ---------------------------------------------------------------------------
create table if not exists listings (
  id                 uuid primary key default gen_random_uuid(),
  seller_id          uuid not null references profiles (id) on delete cascade,
  listing_type       listing_type not null,
  title              text not null,
  author             text,
  description        text,
  condition          book_condition,
  price              numeric(10, 2),        -- sale only; null otherwise
  is_negotiable      boolean not null default false,
  swap_wanted        text,                  -- what the owner wants in return (swap)
  currency           text not null default 'GEL',
  city               text,
  book_language      text,
  genre_id           integer references genres (id) on delete set null,
  isbn               text,
  cover_image_paths  text[] not null default '{}',
  cover_external_url text,                  -- Google Books fallback when no photos
  status             listing_status not null default 'active',
  created_at         timestamptz not null default now(),
  updated_at         timestamptz not null default now(),
  -- combined text used for trigram search
  search_text        text generated always as (
    coalesce(title, '') || ' ' || coalesce(author, '')
  ) stored
);

create index if not exists listings_search_trgm  on listings using gin (search_text gin_trgm_ops);
create index if not exists listings_type_status   on listings (listing_type, status);
create index if not exists listings_created_at     on listings (created_at desc);
create index if not exists listings_city           on listings (city);
create index if not exists listings_genre          on listings (genre_id);

create or replace function public.touch_updated_at()
returns trigger language plpgsql as $$
begin new.updated_at = now(); return new; end;
$$;

drop trigger if exists listings_touch on listings;
create trigger listings_touch before update on listings
  for each row execute function public.touch_updated_at();

-- ---------------------------------------------------------------------------
-- book_alerts  (email-only subscriptions; no in-app notification)
-- ---------------------------------------------------------------------------
create table if not exists book_alerts (
  id         uuid primary key default gen_random_uuid(),
  user_id    uuid not null references profiles (id) on delete cascade,
  title      text,
  author     text,
  isbn       text,
  active     boolean not null default true,
  created_at timestamptz not null default now(),
  constraint book_alerts_has_criteria check (
    coalesce(title, '') <> '' or coalesce(author, '') <> '' or coalesce(isbn, '') <> ''
  )
);
create index if not exists book_alerts_active on book_alerts (active);

-- ---------------------------------------------------------------------------
-- conversations & messages
-- ---------------------------------------------------------------------------
create table if not exists conversations (
  id         uuid primary key default gen_random_uuid(),
  listing_id uuid references listings (id) on delete set null,
  buyer_id   uuid not null references profiles (id) on delete cascade,
  seller_id  uuid not null references profiles (id) on delete cascade,
  created_at timestamptz not null default now(),
  unique (listing_id, buyer_id)
);
create index if not exists conversations_buyer  on conversations (buyer_id);
create index if not exists conversations_seller on conversations (seller_id);

create table if not exists messages (
  id              uuid primary key default gen_random_uuid(),
  conversation_id uuid not null references conversations (id) on delete cascade,
  sender_id       uuid not null references profiles (id) on delete cascade,
  body            text not null,
  read_at         timestamptz,
  created_at      timestamptz not null default now()
);
create index if not exists messages_conversation on messages (conversation_id, created_at);

-- ---------------------------------------------------------------------------
-- notifications  (in-app bell: new messages only)
-- ---------------------------------------------------------------------------
create table if not exists notifications (
  id         uuid primary key default gen_random_uuid(),
  user_id    uuid not null references profiles (id) on delete cascade,
  type       text not null,               -- 'new_message'
  payload    jsonb not null default '{}',
  read_at    timestamptz,
  created_at timestamptz not null default now()
);
create index if not exists notifications_user on notifications (user_id, created_at desc);

-- ---------------------------------------------------------------------------
-- favorites & reports
-- ---------------------------------------------------------------------------
create table if not exists favorites (
  id         uuid primary key default gen_random_uuid(),
  user_id    uuid not null references profiles (id) on delete cascade,
  listing_id uuid not null references listings (id) on delete cascade,
  created_at timestamptz not null default now(),
  unique (user_id, listing_id)
);

create table if not exists reports (
  id          uuid primary key default gen_random_uuid(),
  reporter_id uuid references profiles (id) on delete set null,
  listing_id  uuid not null references listings (id) on delete cascade,

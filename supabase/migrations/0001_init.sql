-- profiles: read own; admins read all. Public seller info comes from public_seller view.
drop policy if exists profiles_select on profiles;
create policy profiles_select on profiles
  for select using (auth.uid() = id or public.is_admin());
drop policy if exists profiles_update on profiles;
create policy profiles_update on profiles
  for update using (auth.uid() = id) with check (auth.uid() = id);
drop policy if exists profiles_insert on profiles;
create policy profiles_insert on profiles
  for insert with check (auth.uid() = id);

-- listings: anyone sees active; owner sees own; admins see all.
drop policy if exists listings_select on listings;
create policy listings_select on listings
  for select using (status = 'active' or seller_id = auth.uid() or public.is_admin());
drop policy if exists listings_insert on listings;
create policy listings_insert on listings
  for insert with check (seller_id = auth.uid());
drop policy if exists listings_update on listings;
create policy listings_update on listings
  for update using (seller_id = auth.uid() or public.is_admin());
drop policy if exists listings_delete on listings;
create policy listings_delete on listings
  for delete using (seller_id = auth.uid() or public.is_admin());

-- book_alerts: fully private to the owner.
drop policy if exists book_alerts_all on book_alerts;
create policy book_alerts_all on book_alerts
  for all using (user_id = auth.uid()) with check (user_id = auth.uid());

-- conversations: only the two parties (or admin).
drop policy if exists conversations_select on conversations;
create policy conversations_select on conversations
  for select using (buyer_id = auth.uid() or seller_id = auth.uid() or public.is_admin());
drop policy if exists conversations_insert on conversations;
create policy conversations_insert on conversations
  for insert with check (buyer_id = auth.uid());

-- messages: readable/insertable only by conversation parties.
drop policy if exists messages_select on messages;
create policy messages_select on messages
  for select using (
    exists (
      select 1 from conversations c
      where c.id = messages.conversation_id
        and (c.buyer_id = auth.uid() or c.seller_id = auth.uid())
    )
  );
drop policy if exists messages_insert on messages;
create policy messages_insert on messages
  for insert with check (
    sender_id = auth.uid()
    and exists (
      select 1 from conversations c
      where c.id = conversation_id
        and (c.buyer_id = auth.uid() or c.seller_id = auth.uid())
    )
  );
drop policy if exists messages_update on messages;
create policy messages_update on messages
  for update using (
    exists (
      select 1 from conversations c
      where c.id = messages.conversation_id
        and (c.buyer_id = auth.uid() or c.seller_id = auth.uid())
    )
  );

-- notifications: private to the owner.
drop policy if exists notifications_select on notifications;
create policy notifications_select on notifications
  for select using (user_id = auth.uid());
drop policy if exists notifications_update on notifications;
create policy notifications_update on notifications
  for update using (user_id = auth.uid());

-- favorites: private to the owner.
drop policy if exists favorites_all on favorites;
create policy favorites_all on favorites
  for all using (user_id = auth.uid()) with check (user_id = auth.uid());

-- reports: any signed-in user can file; only admins can read.
drop policy if exists reports_insert on reports;
create policy reports_insert on reports
  for insert with check (auth.uid() is not null);
drop policy if exists reports_select on reports;
create policy reports_select on reports
  for select using (public.is_admin());

-- ---------------------------------------------------------------------------
-- Search RPC — fuzzy (trigram) + filters + sort. Respects RLS (SECURITY INVOKER).
-- ---------------------------------------------------------------------------
create or replace function public.search_listings(
  q            text default null,
  p_type       listing_type default null,
  p_city       text default null,
  p_min_price  numeric default null,
  p_max_price  numeric default null,
  p_condition  book_condition default null,
  p_language   text default null,
  p_genre      integer default null,
  p_sort       text default 'recent',   -- recent | price_asc | price_desc | relevance
  p_limit      integer default 24,
  p_offset     integer default 0
)
returns setof listings
language sql
stable
as $$
  select *
  from listings l
  where l.status = 'active'
    and (p_type is null or l.listing_type = p_type)
    and (p_city is null or l.city = p_city)
    and (p_condition is null or l.condition = p_condition)
    and (p_language is null or l.book_language = p_language)
    and (p_genre is null or l.genre_id = p_genre)
    and (p_min_price is null or l.price >= p_min_price)
    and (p_max_price is null or l.price <= p_max_price)
    and (
      q is null or q = ''
      or l.search_text ilike '%' || q || '%'
      or l.search_text % q
    )
  order by
    case when p_sort = 'price_asc'  then l.price end asc  nulls last,
    case when p_sort = 'price_desc' then l.price end desc nulls last,
    case when p_sort = 'relevance' and q is not null and q <> ''
         then similarity(l.search_text, q) end desc nulls last,
    l.created_at desc
  limit greatest(p_limit, 1)
  offset greatest(p_offset, 0);
$$;

